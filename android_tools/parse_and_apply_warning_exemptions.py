"""Parses and applies warning exemptions from a build log.

For example, let's say that you had the build log of an Android build in
/tmp/build.log (in the form of a log generated by `m >& /tmp/build.log`, or
unpacking `verbose.log`, or similar).

If you invoke this script like:

$ py/bin/android_tools/parse_and_apply_warning_exemptions \
    --android-tree=/path/to/android/tree/root \
    --bug-number=1234 \
    --build-log=/tmp/build.log \
    --upload-with-topic=my-warning-suppressions \
    --update-summary-file=/tmp/summary.json

It will:

1. Parse your build log for warnings that will soon be fatal.
2. Modify all `bp` targets that will be impacted.
3. Create commits w/ helpful messages (tagged with b/1234) in all git repos
   that were modified.
4. Upload all changes to the git repos from step #3, tagged with the
   `my-warning-suppressions` topic.
5. Write a summary file of all changed projects/targets to `/tmp/summary.json`,
   for further automation.
"""

